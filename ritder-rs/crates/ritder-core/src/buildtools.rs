/// Áp một patch lên nội dung file (tách theo '\n' như build.py); FAIL nếu anchor không khớp.
pub fn apply_patch(content: &str, patch: &Patch) -> Result<String, String> {
    let mut lines: Vec<String> = content.split('\n').map(|s| s.to_string()).collect();
    let idx = lines.iter().position(|l| l.contains(patch.anchor))
        .ok_or_else(|| format!("patch anchor not found in {}: {:?} (KOReader changed? update PATCHES)", patch.file, patch.anchor))?;
    let insert: Vec<String> = patch.text.trim_end_matches('\n').split('\n').map(|s| s.to_string()).collect();
    let at = if patch.after { idx + 1 } else { idx };
    for (i, l) in insert.into_iter().enumerate() { lines.insert(at + i, l); }
    Ok(lines.join("\n"))
}

pub fn lua_string(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n"))
}
/// build_info ở dạng dữ liệu JSON (bản Rust) — tương đương build_info.lua của build.py.
pub fn build_info_json(version: &str, update_url: &str, koreader_version: &str) -> String {
    serde_json::json!({"version": version, "update_url": update_url, "koreader_version": koreader_version})
        .to_string()
}
/// Vẫn sinh được dạng Lua cũ khi cần tương thích (dữ liệu thuần).
pub fn build_info_lua(version: &str, update_url: &str, koreader_version: &str) -> String {
    format!("-- Generated by ritder-tools. Do not edit.\nreturn {{\n    version = {},\n    update_url = {},\n    koreader_version = {},\n}}\n",
        lua_string(version), lua_string(update_url), lua_string(koreader_version))
}

pub fn to_lf(data: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(data.len());
    let mut i = 0;
    while i < data.len() {
        if data[i] == b'\r' && i + 1 < data.len() && data[i + 1] == b'\n' { i += 1; continue; }
        out.push(data[i]); i += 1;
    }
    out
}

/// Tìm member data.tar.* trong file .deb (định dạng ar) — port của deb_data().
pub fn deb_data_member(data: &[u8]) -> Result<Vec<u8>, String> {
    if data.len() < 8 || &data[0..8] != b"!<arch>\n" { return Err("not a .deb".into()); }
    let mut off = 8usize;
    while off + 60 <= data.len() {
        let name = String::from_utf8_lossy(&data[off..off + 16]).trim().trim_end_matches('/').to_string();
        let size: usize = String::from_utf8_lossy(&data[off + 48..off + 58]).trim().parse()
            .map_err(|_| "bad ar header".to_string())?;
        let body = data[off + 60..(off + 60 + size).min(data.len())].to_vec();
        if name.starts_with("data.tar") { return Ok(body); }
        off += 60 + size + (size & 1);
    }
    Err("no data.tar member".into())
}

/// Chuẩn hoá tên member tar: bỏ "./" đầu (như unpack_koreader của build.py).
pub fn strip_dot_slash(name: &str) -> String { name.trim_start_matches("./").to_string() }
pub fn koreader_rel(name: &str) -> Option<String> {
    let n = strip_dot_slash(name);
    let rel = n.strip_prefix("lib/koreader/")?.to_string();
    if rel.is_empty() || rel.starts_with('/') || rel.split('/').any(|p| p == "..") { None } else { Some(rel) }
}

/// make_update.py: bỏ qua thư mục userdata/ và file settings.json ở gốc.
pub fn ota_included(rel: &str) -> bool {
    if rel == "settings.json" { return false; }
    if rel == "userdata" || rel.starts_with("userdata/") { return false; }
    true
}
